UPDATE `rubros` AS r
INNER JOIN `tmp_rubros_caeb_2022` AS t
    ON t.codigo_caeb = r.codigo_caeb
SET
    r.nombre = t.nombre,
    r.nivel_caeb = t.nivel_caeb,
    r.estado = 'ACTIVO',
    r.id_usuario_eliminacion = NULL,
    r.deleted_at = NULL,
    r.updated_at = CURRENT_TIMESTAMP
WHERE
       NOT (r.nombre <=> t.nombre)
    OR NOT (r.nivel_caeb <=> t.nivel_caeb)
    OR NOT (r.estado <=> 'ACTIVO')
    OR r.deleted_at IS NOT NULL;

SET @rubros_caeb_actualizados = ROW_COUNT();

INSERT INTO `rubros` (
    `id_rubro_padre`,
    `codigo_caeb`,
    `nivel_caeb`,
    `nombre`,
    `estado`,
    `id_usuario_registro`,
    `id_usuario_modificacion`,
    `id_usuario_eliminacion`,
    `created_at`,
    `updated_at`,
    `deleted_at`
)
SELECT
    NULL,
    t.codigo_caeb,
    t.nivel_caeb,
    t.nombre,
    'ACTIVO',
    NULL,
    NULL,
    NULL,
    CURRENT_TIMESTAMP,
    CURRENT_TIMESTAMP,
    NULL
FROM `tmp_rubros_caeb_2022` AS t
WHERE NOT EXISTS (
    SELECT 1
    FROM `rubros` AS r
    WHERE r.codigo_caeb = t.codigo_caeb
)
ORDER BY
    FIELD(t.nivel_caeb, 'SECCION', 'DIVISION', 'GRUPO', 'CLASE', 'SUBCLASE'),
    t.codigo_caeb;

SET @rubros_caeb_insertados = ROW_COUNT();

UPDATE `rubros` AS r
INNER JOIN `tmp_rubros_caeb_2022` AS t
    ON t.codigo_caeb = r.codigo_caeb
LEFT JOIN `rubros` AS padre
    ON padre.codigo_caeb = NULLIF(t.codigo_padre, '')
SET
    r.id_rubro_padre = padre.id,
    r.updated_at = CASE
        WHEN NOT (r.id_rubro_padre <=> padre.id) THEN CURRENT_TIMESTAMP
        ELSE r.updated_at
    END
WHERE NOT (r.id_rubro_padre <=> padre.id);

