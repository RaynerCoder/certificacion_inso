-- VERIFICACIONES POSTERIORES A LA IMPORTACI?N
-- Debe devolver cero filas: nombres duplicados dentro del mismo territorio padre.
SELECT `id_padre_territorio`, `nombre`, COUNT(*) AS `cantidad`
FROM `territorios`
GROUP BY `id_padre_territorio`, `nombre`
HAVING COUNT(*) > 1;

-- Debe devolver cero filas: territorios cuyo padre no existe.
SELECT hijo.*
FROM `territorios` AS hijo
LEFT JOIN `territorios` AS padre ON padre.`id` = hijo.`id_padre_territorio`
WHERE hijo.`id_padre_territorio` IS NOT NULL AND padre.`id` IS NULL;

-- Resumen final por ?mbito.
SELECT a.`id`, a.`nombre`, COUNT(t.`id`) AS `cantidad`
FROM `ambitos` AS a
LEFT JOIN `territorios` AS t ON t.`id_ambito` = a.`id`
WHERE a.`id` IN (1, 2, 3)
GROUP BY a.`id`, a.`nombre`
ORDER BY a.`id`;
